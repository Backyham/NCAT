"""Style stage: cues -> bilingual ASS.

Ported from the ``__main__`` block of ``Full-auto_M134A16.py``: same
Nixiesubs look (辉中 / 辉英 styles, the logo lines, the ``setTime(0,0)``
review sentinel) but reading cues instead of argv, and writing the header
from a template rather than a string literal embedded in control flow.

The exported ASS is what Aegisub opens, so the output uses CRLF and a BOM,
matching what Aegisub itself writes.
"""
from __future__ import annotations

import json
from pathlib import Path

from .paths import JobPaths, Report, noop_report
from .segment import ms_to_ass

STYLE_ZH = '辉中'
STYLE_EN = '辉英'
STYLE_NOTE = '辉注'

ASS_HEADER = """[Script Info]
; Script generated by NCAT
Title: Default
ScriptType: v4.00+
WrapStyle: 0
ScaledBorderAndShadow: yes
YCbCr Matrix: TV.601
PlayResX: 1280
PlayResY: 720

[Aegisub Project Garbage]
Last Style Storage: Default

[V4+ Styles]
Format: Name, Fontname, Fontsize, PrimaryColour, SecondaryColour, OutlineColour, BackColour, Bold, Italic, Underline, StrikeOut, ScaleX, ScaleY, Spacing, Angle, BorderStyle, Outline, Shadow, Alignment, MarginL, MarginR, MarginV, Encoding
Style: Default,Sarasa Gothic SC,35,&H00FFFFFF,&H000000FF,&H00000000,&H00000000,0,0,0,0,100,100,0,0,1,0,0,2,0,0,8,1
Style: 辉中,Sarasa Gothic SC,45,&H00FFFFFF,&H000000FF,&H006E4216,&H00000000,-1,0,0,0,100,100,0.5,0,1,2.8,0.2,2,0,0,10,1
Style: 辉英,Lato,35,&H00FFFFFF,&H000000FF,&H003B3C3D,&H00000000,0,0,0,0,100,100,1,0,1,2.8,0.2,2,0,0,10,1
Style: 辉注,Sarasa Gothic SC,36,&H00000000,&H000000FF,&H00FFFFFF,&H00000000,0,0,0,0,100,100,1,0,1,3,0.7,9,10,10,10,1

[Events]
Format: Layer, Start, End, Style, Name, MarginL, MarginR, MarginV, Effect, Text
"""


def _dialogue(start_ms: int, end_ms: int, style: str, text: str) -> str:
    # An unaligned cue is emitted at 0:00:00.00 on purpose: that is the
    # "needs a human" marker the original tooling used, and editors look
    # for it. Do not substitute an interpolated time here.
    return (f'Dialogue: 0,{ms_to_ass(start_ms)},{ms_to_ass(end_ms)},'
            f'{style},,0,0,0,,{text}')


def cues_to_ass(cues: list[dict],
                include_notes: bool = True) -> str:
    # Normalise the header's own newlines to CRLF as well, not just the
    # joins: Aegisub rewrites line endings on save, so a header with bare
    # LF makes an imported file differ from its re-exported self.
    lines = [ASS_HEADER.replace('\n', '\r\n')]
    for cue in cues:
        zh = (cue.get('zh') or '').replace('\n', '\\N')
        en = (cue.get('en') or '').replace('\n', '\\N')
        start = int(cue.get('start_ms', 0))
        end = int(cue.get('end_ms', 0))

        if zh and en:
            # Bilingual by default: Chinese over English, styled apart, the
            # way bilingual releases are published.
            lines.append(_dialogue(start, end, STYLE_ZH,
                                   f'{zh}\\N{{\\r{STYLE_EN}}}{en}'))
        elif zh:
            lines.append(_dialogue(start, end, STYLE_ZH, zh))
        elif en:
            lines.append(_dialogue(start, end, STYLE_EN, en))
        elif include_notes:
            note = cue.get('note') or ''
            if note:
                lines.append(f'Comment: 0,{ms_to_ass(start)},{ms_to_ass(end)},'
                             f'{STYLE_NOTE},,0,0,0,,{note}')
    # CRLF and BOM, so Aegisub round-trips it without a conversion prompt.
    return '\ufeff' + '\r\n'.join(lines) + '\r\n'


def style_cues(job_id: int,
               paths: JobPaths | None = None,
               report: Report = noop_report,
               **_ignored) -> dict:
    if paths is None:
        raise ValueError('style stage requires paths')
    paths.require('cues_json', 'ass')
    if not Path(paths.cues_json).is_file():
        raise FileNotFoundError(f'cue file missing: {paths.cues_json}')

    cues = json.loads(Path(paths.cues_json).read_text(encoding='utf-8'))
    report(f'styling {len(cues)} cues')
    ass = cues_to_ass(cues)
    Path(paths.ass).write_text(ass, encoding='utf-8')
    report(f'wrote {Path(paths.ass).name} ({len(ass)} bytes)')
    return {'cues': len(cues), 'ass': str(paths.ass)}
